struct ImportResult { std::string id, err; };

// shared with the import worker threads. leaked on purpose: a detached worker (e.g. a file dialog still
// open) may outlive main, so this must never be destroyed
struct Shared {
    std::mutex mu;
    std::vector<ImportResult> results;
    std::atomic<int> jobs{0};
    std::atomic<bool> dialogOpen{false};
};
Shared& S = *new Shared;

const ImVec4 kRed(1.0f, 0.38f, 0.38f, 1.0f), kGreen(0.45f, 0.95f, 0.55f, 1.0f), kAccent(0.45f, 0.75f, 1.0f, 1.0f);
constexpr const char* kPhoneTitle = "Upload from phone";

std::string pendingSelect;     // newest arrival / "Use this model" click, consumed by modelLibraryControls
std::string scrollTarget;      // list scrolls this ID into view once
std::string status;            // last import result
bool statusErr = false;
double statusTime = -1e9;
bool phoneOpen = false, phoneOpenRequest = false;
std::set<std::string> fromPhone;  // IDs received from phones this session
int controlsFrame = -10;          // last frame modelLibraryControls ran (the phone window only shows with it)
bool lastAllowSelect = true;
std::string lastSelected;

// --- photo -> AI model window ---
constexpr const char* kAiTitle = "Photo to 3D model (AI)";
bool aiOpen = false, aiOpenRequest = false, aiCancelling = false, aiHandled = false;
std::string photoJpeg;             // newest photo from a phone, kept until replaced
Texture2D photoTex{};
bool havePhoto = false;
double photoTime = -1e9;
char hintBuf[64] = "";
std::set<std::string> fromAi;      // IDs generated by the AI this session
std::string aiStartErr;

void setStatus(const std::string& s, bool err) { status = s, statusErr = err, statusTime = GetTime(); }

// copy + validate files on a worker thread so a big mesh doesn't freeze the UI
void startImports(std::vector<std::string> paths) {
    if (paths.empty()) return;
    S.jobs++;
    std::thread([paths = std::move(paths)] {
        for (const auto& p : paths) {
            ImportResult r;
            r.id = modelsImportFile(p, r.err);
            std::lock_guard<std::mutex> l(S.mu);
            S.results.push_back(std::move(r));
        }
        S.jobs--;
    }).detach();
}

void openFileDialog() {
    if (S.dialogOpen.exchange(true)) return;
    if (!fileDialogAvailable()) {
        S.dialogOpen = false;
        setStatus("No file dialog available on this system - drag the file onto the window instead.", true);
        return;
    }
    S.jobs++;
    std::thread([] {
        std::vector<std::string> files = fileDialogOpenModels(); // blocks until the dialog closes
        S.dialogOpen = false;
        for (const auto& p : files) {
            ImportResult r;
            r.id = modelsImportFile(p, r.err);
            std::lock_guard<std::mutex> l(S.mu);
            S.results.push_back(std::move(r));
        }
        S.jobs--;
    }).detach();
}

// --- QR code (cached per URL) ---
std::string qrFor;
std::vector<bool> qrModules;
int qrSize = 0;

void drawQr(const std::string& text, float maxPx) {
    if (text != qrFor) {
        qrFor = text;
        qrModules.clear();
        qrSize = 0;
        try {
            auto qr = qrcodegen::QrCode::encodeText(text.c_str(), qrcodegen::QrCode::Ecc::MEDIUM);
            qrSize = qr.getSize();
            qrModules.resize((size_t)qrSize * qrSize);
            for (int y = 0; y < qrSize; ++y)
                for (int x = 0; x < qrSize; ++x) qrModules[(size_t)y * qrSize + x] = qr.getModule(x, y);
        } catch (...) {}
    }
    if (qrSize == 0) { ImGui::TextColored(kRed, "Couldn't make a QR code."); return; }
    const int quiet = 4; // the spec's quiet zone, scanners need it
    float px = std::floor(maxPx / (qrSize + 2 * quiet)); // whole pixels per module keep it crisp
    if (px < 1.0f) px = 1.0f;
    float total = px * (qrSize + 2 * quiet);
    ImVec2 o = ImGui::GetCursorScreenPos();
    ImDrawList* dl = ImGui::GetWindowDrawList();
    dl->AddRectFilled(o, ImVec2(o.x + total, o.y + total), IM_COL32(255, 255, 255, 255), 8.0f);
    for (int y = 0; y < qrSize; ++y)
        for (int x = 0; x < qrSize; ++x)
            if (qrModules[(size_t)y * qrSize + x]) {
                ImVec2 a(o.x + (x + quiet) * px, o.y + (y + quiet) * px);
                dl->AddRectFilled(a, ImVec2(a.x + px, a.y + px), IM_COL32(0, 0, 0, 255));
            }
    ImGui::Dummy(ImVec2(total, total));
}

void drawPhoneWindow(const UiState& ui) {
    if (phoneOpenRequest) {
        phoneOpenRequest = false;
        ImGui::OpenPopup(kPhoneTitle);
    }
    ImGui::SetNextWindowPos(ImVec2(GetScreenWidth() * 0.5f, GetScreenHeight() * 0.5f), ImGuiCond_Appearing, ImVec2(0.5f, 0.5f));
    ImGui::SetNextWindowSize(ImVec2(600, 0), ImGuiCond_Appearing);
    if (!ImGui::BeginPopupModal(kPhoneTitle, &phoneOpen, ImGuiWindowFlags_NoSavedSettings)) {
        phoneOpen = false;
        return;
    }
    std::string url = serverUrl();

    ImGui::BeginGroup();
    if (url.empty()) ImGui::TextColored(kRed, "Upload server isn't running.");
    else drawQr(url, 230.0f);
    ImGui::EndGroup();
    ImGui::SameLine(0, 20);

    ImGui::BeginGroup();
    ImGui::PushTextWrapPos(ImGui::GetCursorPosX() + 300.0f);
    ImGui::TextColored(kAccent, "Send a model from your phone");
    ImGui::Spacing();
    ImGui::TextWrapped("1. Connect your phone to the same Wi-Fi as this computer.");
    ImGui::TextWrapped("2. Scan the code with the camera app.");
    ImGui::TextWrapped("3. Choose a %s file and tap Upload.", kModelExtsHint);
    ImGui::Spacing();
    ImGui::TextDisabled("Or open this address in a browser:");
    ImGui::Text("%s", url.c_str());
    ImGui::SameLine();
    if (ImGui::SmallButton("Copy")) ImGui::SetClipboardText(url.c_str());
    ImGui::Spacing();
    std::string err = serverError();
    if (!err.empty()) ImGui::TextColored(kRed, "%s", err.c_str());
    else if (!serverHasLan()) ImGui::TextColored(kRed, "No network found - phones can't reach this computer right now.");
    else if (serverListening()) {
        int dots = (int)(GetTime() * 2.0) % 4;
        ImGui::TextDisabled("Waiting for uploads%.*s", dots, "...");
    }
    ImGui::PopTextWrapPos();
    ImGui::EndGroup();

    ImGui::Spacing();
    ImGui::SeparatorText("My models");
    if (ImGui::BeginChild("##phonefiles", ImVec2(-FLT_MIN, 170), ImGuiChildFlags_Borders)) {
        bool any = false;
        for (int i = 0; i < (int)ui.models.size(); ++i) {
            const std::string& id = ui.models[i];
            if (!modelIsCustom(id)) continue;
            any = true;
            ImGui::PushID(i);
            ImGui::AlignTextToFramePadding();
            ImGui::TextUnformatted(modelLabel(id).c_str());
            if (fromPhone.count(id)) {
                ImGui::SameLine();
                ImGui::TextColored(kGreen, "from phone");
            }
            float bw = 140.0f;
            float afterText = ImGui::GetItemRectMax().x - ImGui::GetWindowPos().x + ImGui::GetStyle().ItemSpacing.x;
            ImGui::SameLine(std::max(afterText, ImGui::GetContentRegionMax().x - bw));
            if (id == lastSelected) {
                ImGui::AlignTextToFramePadding();
                ImGui::TextColored(kGreen, "Selected");
            } else {
                ImGui::BeginDisabled(!lastAllowSelect);
                if (ImGui::Button("Use this model", ImVec2(bw, 0))) {
                    pendingSelect = id;
                    phoneOpen = false;
                    ImGui::CloseCurrentPopup();
                }
                ImGui::EndDisabled();
            }
            ImGui::PopID();
        }
        if (!any) ImGui::TextDisabled("Nothing here yet - files you upload will appear here.");
    }
    ImGui::EndChild();

    if (!status.empty() && GetTime() - statusTime < 15.0)
        ImGui::TextColored(statusErr ? kRed : kGreen, "%s", status.c_str());
    if (ImGui::Button("Done", ImVec2(120, 0))) {
        phoneOpen = false;
        ImGui::CloseCurrentPopup();
    }
    ImGui::EndPopup();
}


void setPhoto(const std::string& jpeg) {
    Image img = LoadImageFromMemory(".jpg", (const unsigned char*)jpeg.data(), (int)jpeg.size());
    if (!img.data) {
        setStatus("The photo from your phone couldn't be read - try taking it again.", true);
        return;
    }
    if (havePhoto) UnloadTexture(photoTex);
    photoTex = LoadTextureFromImage(img);
    UnloadImage(img);
    havePhoto = true;
    photoJpeg = jpeg;
    photoTime = GetTime();
    aiStartErr.clear();
}

void drawAiWindow() {
    if (aiOpenRequest) {
        aiOpenRequest = false;
        ImGui::OpenPopup(kAiTitle);
    }
    ImGui::SetNextWindowPos(ImVec2(GetScreenWidth() * 0.5f, GetScreenHeight() * 0.5f), ImGuiCond_Appearing, ImVec2(0.5f, 0.5f));
    ImGui::SetNextWindowSize(ImVec2(620, 0), ImGuiCond_Appearing);
    if (!ImGui::BeginPopupModal(kAiTitle, &aiOpen, ImGuiWindowFlags_NoSavedSettings)) {
        aiOpen = false;
        return;
    }
    AiStatus st = aiStatus();
    const bool busy = aiBusy();
    if (!busy) aiCancelling = false;
    const bool hasKey = !settingsApiKey().empty();

    // left: QR for the phone page; right: the photo once it arrives, else the instructions
    std::string url = serverUrl();
    std::string camUrl = url.empty() ? "" : url + "/camera";
    ImGui::BeginGroup();
    if (camUrl.empty()) ImGui::TextColored(kRed, "Upload server isn't running.");
    else drawQr(camUrl, 210.0f);
    ImGui::EndGroup();
    ImGui::SameLine(0, 20);

    ImGui::BeginGroup();
    ImGui::PushTextWrapPos(ImGui::GetCursorPosX() + 330.0f);
    if (!havePhoto) {
        ImGui::TextColored(kAccent, "Take a photo with your phone");
        ImGui::Spacing();
        ImGui::TextWrapped("1. Connect your phone to the same Wi-Fi as this computer.");
        ImGui::TextWrapped("2. Scan the code and tap the camera button.");
        ImGui::TextWrapped("3. Photograph one object, then tap Send.");
        ImGui::Spacing();
        std::string err = serverError();
        if (!err.empty()) ImGui::TextColored(kRed, "%s", err.c_str());
        else if (!serverHasLan()) ImGui::TextColored(kRed, "No network found - phones can't reach this computer right now.");
        else if (serverListening()) ImGui::TextDisabled("Waiting for a photo%.*s", (int)(GetTime() * 2.0) % 4, "...");
    } else {
        ImGui::TextColored(kGreen, "Photo received");
        float maxW = 240.0f, maxH = 170.0f;
        float sc = std::min(maxW / photoTex.width, maxH / photoTex.height);
        rlImGuiImageSize(&photoTex, (int)(photoTex.width * sc), (int)(photoTex.height * sc));
        ImGui::TextDisabled("Not right? Scan again to send a new one.");
    }
    ImGui::PopTextWrapPos();
    ImGui::EndGroup();

    ImGui::Spacing();
    ImGui::SetNextItemWidth(-FLT_MIN);
    ImGui::BeginDisabled(busy);
    ImGui::InputTextWithHint("##hint", "What is it? (optional, e.g. paper airplane)", hintBuf, sizeof hintBuf);
    ImGui::EndDisabled();
    ImGui::Spacing();

    if (!hasKey) {
        ImGui::TextColored(kRed, "No API key set.");
        ImGui::SameLine();
        if (ImGui::SmallButton("Open Settings")) {
            aiOpen = false; // settings is its own window, this one is restored from the model screen
            settingsUiRequestOpen();
            ImGui::CloseCurrentPopup();
        }
    }

    if (busy) {
        const char* label = aiCancelling ? "Cancelling..." :
            st.phase == AiPhase::Sending ? "Sending the photo..." :
            st.phase == AiPhase::Thinking ? "The AI is studying the photo..." :
            st.phase == AiPhase::Writing ? "Building the model..." : "Checking the model...";
        ImGui::TextUnformatted(label);
        char overlay[64];
        std::snprintf(overlay, sizeof overlay, "%d s", (int)st.elapsed);
        float frac = st.phase == AiPhase::Writing ? std::min(0.95f, st.vertices / 300.0f) : -1.0f * (float)ImGui::GetTime();
        ImGui::ProgressBar(frac, ImVec2(-FLT_MIN, 0), overlay);
        if (st.phase == AiPhase::Writing) ImGui::TextDisabled("%d points, %d triangles so far", st.vertices, st.faces);
        else ImGui::TextDisabled("This usually takes 30-90 seconds.");
        if (st.attempt > 1) ImGui::TextColored(kAccent, "The first try didn't load - asking the AI to fix it.");
        ImGui::BeginDisabled(aiCancelling);
        if (ImGui::Button("Cancel", ImVec2(120, 0))) {
            aiCancel();
            aiCancelling = true;
        }
        ImGui::EndDisabled();
    } else {
        if (st.phase == AiPhase::Done)
            ImGui::TextColored(kGreen, "Made %s - it's selected in the model list.", modelLabel(st.modelId).c_str());
        else if (st.phase == AiPhase::Failed) {
            ImGui::PushTextWrapPos(ImGui::GetCursorPosX() + 570.0f);
            ImGui::TextColored(kRed, "%s", st.error.c_str());
            ImGui::PopTextWrapPos();
        } else if (st.phase == AiPhase::Cancelled) ImGui::TextDisabled("Cancelled.");
        if (!aiStartErr.empty()) ImGui::TextColored(kRed, "%s", aiStartErr.c_str());

        bool again = st.phase == AiPhase::Failed || st.phase == AiPhase::Cancelled;
        ImGui::BeginDisabled(!havePhoto || !hasKey);
        if (ImGui::Button(again ? "Try again" : st.phase == AiPhase::Done ? "Make another" : "Generate model", ImVec2(170, 0))) {
            aiStartErr.clear();
            aiHandled = false;
            if (!aiStart(photoJpeg, hintBuf, aiStartErr)) aiHandled = true;
        }
        ImGui::EndDisabled();
        if (!havePhoto && ImGui::IsItemHovered(ImGuiHoveredFlags_AllowWhenDisabled)) ImGui::SetTooltip("Send a photo from your phone first");
        ImGui::SameLine();
        if (ImGui::Button(st.phase == AiPhase::Done ? "Done" : "Close", ImVec2(120, 0))) {
            if (st.phase != AiPhase::Idle) aiAcknowledge();
            aiOpen = false;
            ImGui::CloseCurrentPopup();
        }
    }
    ImGui::EndPopup();
}

